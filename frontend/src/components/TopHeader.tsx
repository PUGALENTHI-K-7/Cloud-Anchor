import {
  RefreshCw,
  Cpu,
  Cloud,
  Server
} from "lucide-react";
import type { DashboardMetrics, NavTab } from "../types/dashboard";

interface TopHeaderProps {
  activeTab: NavTab;
  metrics: DashboardMetrics | null;
  gatewayError: string | null;
  loading: boolean;
  onRefresh: () => void;
}

export const TopHeader: React.FC<TopHeaderProps> = ({
  activeTab,
  metrics,
  gatewayError,
  loading,
  onRefresh,
}) => {
  const isCloudOnline = metrics?.cloud_api?.status === "ONLINE";
  const isGatewayOnline = !gatewayError && metrics !== null;
  const activeDevice = metrics?.latest_telemetry?.device_id || "ARDUINO-001";
  const lastUpdatedSec = metrics?.latest_telemetry?.last_updated_sec_ago ?? 0;
  const isStale = lastUpdatedSec > 15;

  const pageHeadings: Record<NavTab, { title: string; subtitle: string }> = {
    overview: {
      title: "Overview",
      subtitle: "Live sensor and system status",
    },
    sensors: {
      title: "Sensors",
      subtitle: "Live measurements generated by the Arduino sensor simulation.",
    },
    data_calc: {
      title: "Data & Calculation",
      subtitle: "Understand where each telemetry value comes from and how derived values are calculated.",
    },
    system: {
      title: "System",
      subtitle: "Hardware node status, local SQLite storage, and cloud synchronization state.",
    },
  };

  const current = pageHeadings[activeTab] || pageHeadings.overview;

  return (
    <header className="border-b border-[#253247] bg-[#0B1220]/95 backdrop-blur sticky top-0 z-30 px-6 py-3.5">
      <div className="flex flex-wrap items-center justify-between gap-4">
        
        {/* Left: Page Title and Descriptive Subtitle */}
        <div>
          <h1 className="text-base font-bold text-slate-100 font-sans tracking-tight">
            {current.title}
          </h1>
          <p className="text-xs text-slate-400 font-sans mt-0.5">
            {current.subtitle}
          </p>
        </div>

        {/* Right: Compact Status Badges & Refresh */}
        <div className="flex items-center gap-2.5 flex-wrap text-xs font-mono">
          
          {/* Request Number Badge */}
          <div className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-[#151F2E] border border-[#253247] text-slate-300">
            <span className="text-slate-400 font-sans text-[11px]">Request Number</span>
            <span className="font-bold text-cyan-400 font-mono">
              {metrics?.latest_telemetry?.request_id || "—"}
            </span>
          </div>

          {/* Arduino Sensor Node Badge */}
          <div className="flex items-center gap-2 px-3 py-1.5 rounded-lg bg-[#151F2E] border border-[#253247] text-slate-300">
            <Cpu className="w-3.5 h-3.5 text-cyan-400" />
            <div className="flex items-center gap-1.5">
              <span className="text-slate-400 font-sans text-[11px]">Node</span>
              <span className="font-bold text-slate-200">{activeDevice}</span>
            </div>
            <span className={`px-1.5 py-0.2 text-[10px] font-bold rounded ${
              !isStale && isGatewayOnline && metrics?.latest_telemetry ? "bg-emerald-500/20 text-emerald-400" : metrics?.latest_telemetry ? "bg-amber-500/20 text-amber-400" : "bg-slate-700 text-slate-400"
            }`}>
              {!isStale && isGatewayOnline && metrics?.latest_telemetry ? "● LIVE" : metrics?.latest_telemetry ? "STALE" : "WAITING"}
            </span>
          </div>

          {/* Gateway Status */}
          <div className={`flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg border ${
            isGatewayOnline
              ? "bg-emerald-500/10 text-emerald-400 border-emerald-500/25"
              : "bg-red-500/10 text-red-400 border-red-500/25"
          }`}>
            <Server className="w-3.5 h-3.5" />
            <span>Gateway: {isGatewayOnline ? "ONLINE" : "OFFLINE"}</span>
          </div>

          {/* Cloud Status */}
          <div className={`flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg border ${
            isCloudOnline
              ? "bg-emerald-500/10 text-emerald-400 border-emerald-500/25"
              : "bg-red-500/10 text-red-400 border-red-500/25"
          }`}>
            <Cloud className="w-3.5 h-3.5" />
            <span>Cloud: {isCloudOnline ? "ONLINE" : "OFFLINE"}</span>
          </div>

          {/* Data Freshness Status */}
          <div className={`flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg border ${
            !isStale && isGatewayOnline && metrics?.latest_telemetry
              ? "bg-emerald-500/10 text-emerald-400 border-emerald-500/25"
              : "bg-amber-500/10 text-amber-400 border-amber-500/25"
          }`}>
            <span>Data: {!isStale && isGatewayOnline && metrics?.latest_telemetry ? "LIVE" : metrics?.latest_telemetry ? "STALE" : "WAITING"}</span>
          </div>

          {/* Manual Refresh Button */}
          <button
            onClick={onRefresh}
            title="Refresh telemetry"
            className="p-2 rounded-lg bg-[#151F2E] hover:bg-[#1E293B] border border-[#253247] text-slate-300 hover:text-white transition flex items-center gap-1"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${loading ? "animate-spin text-cyan-400" : ""}`} />
          </button>

        </div>

      </div>
    </header>
  );
};
